import sys
import json
from datetime import datetime
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
)

if len(sys.argv) != 3:
    raise SystemExit("Usage: generate-msme-pdf.py input.json output.pdf")

with open(sys.argv[1], "r", encoding="utf-8") as f:
    report = json.load(f)

pdfmetrics.registerFont(
    TTFont("Tamil", "public/assets/sasikumar-tamil.ttf")
)

styles = getSampleStyleSheet()
styles.add(ParagraphStyle(
    name="TitleTamil",
    fontName="Tamil",
    fontSize=17,
    leading=23,
    alignment=TA_CENTER,
    textColor=colors.HexColor("#174A7E"),
    spaceAfter=5*mm
))
styles.add(ParagraphStyle(
    name="TamilBody",
    fontName="Tamil",
    fontSize=9,
    leading=14
))
styles.add(ParagraphStyle(
    name="TamilSmall",
    fontName="Tamil",
    fontSize=8,
    leading=11
))
styles.add(ParagraphStyle(
    name="TamilCenter",
    fontName="Tamil",
    fontSize=10,
    leading=15,
    alignment=TA_CENTER
))

doc = SimpleDocTemplate(
    sys.argv[2],
    pagesize=A4,
    rightMargin=15*mm,
    leftMargin=15*mm,
    topMargin=15*mm,
    bottomMargin=15*mm
)

story = []
story.append(Paragraph(
    "TAMIL NADU MSME DISTRICT REPORT",
    styles["TitleTamil"]
))
story.append(Paragraph(
    "தமிழ்நாடு மாவட்ட வாரியான குறு, சிறு மற்றும் நடுத்தரத் தொழில் நிறுவனங்கள்",
    styles["TamilCenter"]
))
story.append(Spacer(1, 4*mm))

checked = report.get("checkedAt", "")
try:
    checked = datetime.fromisoformat(
        checked.replace("Z", "+00:00")
    ).astimezone().strftime("%d-%m-%Y %I:%M %p")
except Exception:
    checked = datetime.now().strftime("%d-%m-%Y %I:%M %p")

total = int(report.get("stateTotal", 0))
story.append(Paragraph(
    f"<b>State / மாநிலம்:</b> Tamil Nadu / தமிழ்நாடு<br/>"
    f"<b>Total UDYAM registrations / மொத்தப் பதிவு:</b> {total:,}<br/>"
    f"<b>Report checked / சரிபார்த்த நேரம்:</b> {checked}",
    styles["TamilBody"]
))
story.append(Spacer(1, 5*mm))

rows = [[
    Paragraph("S.No.", styles["TamilBody"]),
    Paragraph("District / மாவட்டம்", styles["TamilBody"]),
    Paragraph("UDYAM Registrations / பதிவுகள்", styles["TamilBody"])
]]

for i, district in enumerate(report.get("districts", []), 1):
    name = district.get("name", "")
    tamil = district.get("tamil", "")
    count = int(district.get("total", 0))
    rows.append([
        str(i),
        Paragraph(f"{name}<br/>{tamil}", styles["TamilBody"]),
        f"{count:,}"
    ])

rows.append([
    "",
    Paragraph("<b>STATE TOTAL / மாநில மொத்தம்</b>", styles["TamilBody"]),
    f"<b>{total:,}</b>"
])

table = Table(rows, colWidths=[18*mm, 85*mm, 75*mm], repeatRows=1)
table.setStyle(TableStyle([
    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#DCEBFA")),
    ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#17365D")),
    ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#AAB7C4")),
    ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ("ALIGN", (0, 0), (0, -1), "CENTER"),
    ("ALIGN", (2, 1), (2, -1), "RIGHT"),
    ("ROWBACKGROUNDS", (0, 1), (-1, -2),
     [colors.white, colors.HexColor("#F3F7FB")]),
    ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#E4F2E8")),
    ("TOPPADDING", (0, 0), (-1, -1), 5),
    ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
]))
story.append(table)
story.append(Spacer(1, 6*mm))

story.append(Paragraph(
    "Source / ஆதாரம்: Data.gov.in — List of MSME Registered Units under UDYAM.",
    styles["TamilSmall"]
))
story.append(Paragraph(
    "Note / குறிப்பு: இவை UDYAM பதிவுகளின் எண்ணிக்கை. "
    "இது தற்போது செயல்பாட்டில் உள்ள நிறுவனங்களின் எண்ணிக்கைக்கு சமம் என்று கருதக்கூடாது.",
    styles["TamilSmall"]
))
story.append(Paragraph(
    "Generated by SASIKUMAR AI",
    styles["TamilCenter"]
))

doc.build(story)
print("PDF_CREATED", sys.argv[2])
