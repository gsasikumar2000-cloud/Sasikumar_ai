function detectContentLanguage(text) {
  const s = String(text || '');

  const tamil = (s.match(/[\u0B80-\u0BFF]/g) || []).length;
  const latin = (s.match(/[A-Za-z]/g) || []).length;

  if (tamil > 0 && latin > 0) return 'Tamil-English mixed';
  if (tamil > 0) return 'Tamil';
  return 'English';
}

function cleanText(text, max = 4000) {
  return String(text || '').trim().slice(0, max);
}

function buildPosterPrompt(content, reply, language) {
  return `
Create a clean professional social-media poster for SASIKUMAR AI.

Content:
${content}

AI Reply:
${reply}

Language:
${language}

Poster requirements:
- Clear readable headline
- Modern professional design
- Suitable for WhatsApp/social media sharing
- Include "SASIKUMAR AI"
- Do not invent prices, dates, statistics, names, phone numbers, or claims
- Do not add unrelated information
- Use the same language style as the content when practical
- Keep text short and visually readable
- No watermark other than SASIKUMAR AI
`.trim();
}


function escapeXml(text) {
  return String(text || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function wrapPosterText(text, maxChars = 34) {
  const words = String(text || '').split(/\s+/);
  const lines = [];
  let line = '';

  for (const word of words) {
    const next = line ? line + ' ' + word : word;
    if (next.length > maxChars && line) {
      lines.push(line);
      line = word;
    } else {
      line = next;
    }
  }

  if (line) lines.push(line);
  return lines.slice(0, 8);
}

async function createLocalSvgPoster(content, reply, language, theme = "classic") {
  const fs = require('fs');
  const path = require('path');

  const outDir = path.join(__dirname, 'public', 'generated');
  fs.mkdirSync(outDir, { recursive: true });

  const id = Date.now();
  const filename = `any-content-${id}.svg`;
  const filePath = path.join(outDir, filename);

  const contentLines = wrapPosterText(content, 38);

  const posterTheme = normalizePosterTheme(theme);
  const colors = POSTER_THEMES[posterTheme];

  const contentSvg = contentLines.map((line, i) =>
    `<text x="60" y="${235 + i * 34}" class="body" fill="${colors.text}">${escapeXml(line)}</text>`
  ).join('');



  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1080" viewBox="0 0 1080 1080">
  <rect width="1080" height="1080" rx="42" fill="${colors.bg}"/>
  <rect x="30" y="30" width="1020" height="1020" rx="34" fill="${colors.card}" stroke="${colors.accent}" stroke-width="4"/>

  <text x="60" y="105" class="brand" fill="${colors.accent}">SASIKUMAR AI</text>
  <text x="60" y="155" class="title" fill="${colors.text}">AI CONTENT UPDATE</text>
  <text x="60" y="195" class="lang" fill="${colors.muted}">${escapeXml(language)}</text>

  <text x="60" y="220" class="section" fill="${colors.accent}">CONTENT</text>
  ${contentSvg}



  <text x="60" y="1015" class="footer" fill="${colors.muted}">Generated by SASIKUMAR AI</text>

  <style>
    .brand { font: 700 48px Arial, sans-serif; fill: #111111; }
    .title { font: 700 34px Arial, sans-serif; fill: #333333; }
    .lang { font: 500 24px Arial, sans-serif; fill: #666666; }
    .section { font: 700 24px Arial, sans-serif; fill: #555555; }
    .body { font: 400 29px Arial, sans-serif; fill: #111111; }
    .footer { font: 500 22px Arial, sans-serif; fill: #777777; }
  </style>
</svg>`;

  fs.writeFileSync(filePath, svg, 'utf8');
  return `/generated/${filename}`;
}

async function createAnyContentResult({
  content,
  askAI,
  generateAIImage,
  theme = "classic"
}) {
  const text = cleanText(content);

  if (!text) {
    throw new Error('Content is required');
  }

  if (typeof askAI !== 'function') {
    throw new Error('AI reply function is unavailable');
  }

  if (typeof generateAIImage !== 'function') {
    throw new Error('AI image function is unavailable');
  }

  const language = detectContentLanguage(text);
  const posterTheme = normalizePosterTheme(theme);

  const replyPrompt = `
You are SASIKUMAR AI.

Reply to the user's content clearly and naturally.

Language rules:
- Tamil → reply in Tamil
- English → reply in English
- Tamil-English mixed → natural Tamil-English mixed reply
- Do not unnecessarily change the user's language
- Do not invent facts
- Keep the reply useful and concise

User content:
${text}
`.trim();

  const reply = await askAI(replyPrompt, language);

  const imagePrompt = buildPosterPrompt(text, reply, language);

  let imageUrl = null;
  let posterAvailable = false;
  let posterError = null;

  try {
    imageUrl = await generateAIImage(imagePrompt);
    posterAvailable = Boolean(imageUrl);
  } catch (error) {
    const exactError = String(error?.message || error || 'Image generation failed');
    console.warn('⚠️ Any Content AI poster unavailable:', exactError);

    try {
      imageUrl = await createLocalSvgPoster(text, reply, language, posterTheme);
      posterAvailable = Boolean(imageUrl);
      posterError = posterAvailable
        ? 'AI poster unavailable; local poster generated successfully.'
        : 'Poster generation unavailable right now.';
    } catch (localError) {
      posterError = String(localError?.message || localError || 'Poster generation failed');
      console.warn('⚠️ Any Content local SVG poster failed:', posterError);
    }
  }

  return {
    ok: true,
    type: 'any-content',
    language,
    content: text,
    reply,
    posterTheme,
    posterAvailable,
    imageUrl,
    ...(posterError ? { posterError } : {})
  };
}

